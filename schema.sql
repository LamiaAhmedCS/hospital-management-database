-- 1. Department Table
CREATE TABLE DEPARTMENT (
    DEP_ID NUMBER PRIMARY KEY,
    DEP_NAME VARCHAR2(50) NOT NULL,
    NUM_FLOOR NUMBER
);

-- 2. Doctor Table
CREATE TABLE DOCTOR (
    DR_ID NUMBER,
    DR_NAME VARCHAR2(30) NOT NULL,
    SPECIALTY VARCHAR2(50),
    HIRE_DATE DATE,
    DEP_ID NUMBER NOT NULL,

    CONSTRAINT DRPK PRIMARY KEY (DR_ID),
    CONSTRAINT DRFK FOREIGN KEY (DEP_ID)
        REFERENCES DEPARTMENT(DEP_ID)
);

-- 3. Patient Table
CREATE TABLE PATIENT (
    P_ID NUMBER PRIMARY KEY,
    P_NAME VARCHAR2(50) NOT NULL,
    GENDER VARCHAR2(10),
    BIRTH_DATE DATE,
    PHONE VARCHAR2(20),
    ADDRESS VARCHAR2(100)
);

-- 4. Appointment Table
CREATE TABLE APPOINTMENT (
    APP_ID NUMBER PRIMARY KEY,
    APP_DATE DATE NOT NULL,
    DIAGNOSIS VARCHAR2(100),
    APP_COST NUMBER(8,2),
    P_ID NUMBER NOT NULL,
    DR_ID NUMBER NOT NULL,

    CONSTRAINT FK_APP_PATIENT FOREIGN KEY (P_ID)
        REFERENCES PATIENT(P_ID),

    CONSTRAINT FK_APP_DOCTOR FOREIGN KEY (DR_ID)
        REFERENCES DOCTOR(DR_ID)
);

-- 5. Treatment Table
CREATE TABLE TREATMENT (
    T_ID NUMBER PRIMARY KEY,
    NAME_T VARCHAR2(50) NOT NULL,
    T_TYPE VARCHAR2(30),
    T_COST NUMBER(8,2)
);

-- 6. Receive Table
CREATE TABLE RECEIVE (
    P_ID NUMBER NOT NULL,
    T_ID NUMBER NOT NULL,
    START_DATE DATE,
    END_DATE DATE,

    CONSTRAINT PK_RECEIVE
        PRIMARY KEY (P_ID, T_ID, START_DATE),

    CONSTRAINT FK_RECEIVE_PATIENT
        FOREIGN KEY (P_ID)
        REFERENCES PATIENT(P_ID),

    CONSTRAINT FK_RECEIVE_TREATMENT
        FOREIGN KEY (T_ID)
        REFERENCES TREATMENT(T_ID)
);